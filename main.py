# main.py
import os
import sys
import json

# Force line buffering so you can see traceback updates immediately in the dashboard console
sys.stdout.reconfigure(line_buffering=True)
sys.stderr.reconfigure(line_buffering=True)

try:
    from mcp.server.mcpserver import MCPServer
    mcp = MCPServer("HDRS-RAG-Retrieve")
except Exception as init_err:
    print(f"CRITICAL: MCP v2 Server initialization failed: {init_err}", file=sys.stderr)
    sys.exit(1)

@mcp.tool()
def query_knowledge_base(question: str) -> str:
    """
    Search and retrieve answers from the Astra DB Vector Store RAG knowledge base using OpenRouter.
    """
    # Defensive layout checks
    if not os.path.exists("flow.json"):
        return "ERROR: flow.json layout configuration file is missing from the server root directory."

    try:
        # Keep runtime imports scoped strictly inside the tool execution thread 
        # to ensure the baseline MCP server boots instantly and bypasses container launch timeouts
        from langflow.load import run_flow_from_json
        
        print(f"INFO: Orchestrating Langflow graph for question: '{question}'")
        
        # Natively executes the HDRS RAG workflow layout structure
        result = run_flow_from_json(
            flow="flow.json",
            input_value=question
        )
        
        # Parse the structured text message out of the compiled graph execution blocks
        if result and len(result) > 0:
            # Safely navigate the nested Message/Data output structures generated by the Agent node
            try:
                return result[0].outputs[0].results["message"].text
            except (AttributeError, KeyError, IndexError):
                # Fallback to string stringification for structural stability
                return str(result)
                
        return "No response generated by the Langflow pipeline."
        
    except Exception as run_err:
        print(f"ERROR: Runtime graph execution failure: {run_err}", file=sys.stderr)
        return f"Error executing Langflow graph pipeline: {str(run_err)}"

if __name__ == "__main__":
    try:
        mcp.run()
    except Exception as runtime_err:
        print(f"CRITICAL: Underlying runtime engine crashed: {runtime_err}", file=sys.stderr)

