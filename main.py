import os
import sys
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from mcp.server.fastmcp import FastMCP

# Force line buffering so debugging text logs instantly inside the Render panel
sys.stdout.reconfigure(line_buffering=True)
sys.stderr.reconfigure(line_buffering=True)

# 1. Initialize FastMCP and register your RAG tool workflow
mcp = FastMCP("HDRS-RAG-Retrieve")

@mcp.tool()
def query_knowledge_base(question: str) -> str:
    """
    Search and retrieve answers from the Astra DB Vector Store RAG knowledge base using OpenRouter.
    """
    try:
        from langflow.load import run_flow_from_json
        
        if not os.path.exists("flow.json"):
            return "Error: flow.json layout configuration file is missing from the server root directory."

        print(f"INFO: Executing Langflow flow for question: {question}")
        result = run_flow_from_json(
            flow="flow.json",
            input_value=question
        )
        
        if result and len(result) > 0:
            return result.outputs.results["message"].text
        return "No response generated by the Langflow pipeline."
        
    except Exception as e:
        print(f"ERROR: Runtime execution failure: {e}", file=sys.stderr)
        return f"Error executing Langflow graph: {str(e)}"

# 2. Extract the native underlying web application structure (FastAPI/Starlette wrapper)
# This hooks up all internal protocol paths (/sse, /messages) correctly at the root level.
app = mcp.sse_app()

# 3. Add wide-open CORS security context so external browser test suites can read the SSE stream
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# 4. Bind a native root endpoint to fulfill Render's platform monitoring health check requirements
@app.get("/")
async def health_check():
    return {"status": "healthy", "service": "HDRS-RAG-Retrieve-MCP"}

if __name__ == "__main__":
    mcp.run()
